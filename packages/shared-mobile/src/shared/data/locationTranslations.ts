/**
 * Returns the localised display name for a state, district, or block.
 * Falls back: requested language → Hindi → English key.
 */
export function getLocationDisplayName(
  name: string,
  type: 'state' | 'district' | 'block',
  lang: string,
): string {
  const code = lang.split('-')[0];

  // English → always return the original English key (no translation needed)
  if (code === 'en') return name;

  const map =
    type === 'state'
      ? stateTranslations
      : type === 'district'
      ? districtTranslations
      : blockTranslations;
  const entry = map[name];
  if (!entry) return name;

  // For states: always fall back to Hindi (all states are translated in all langs).
  if (type === 'state') return entry[code] ?? entry['hi'] ?? name;

  // For districts/blocks:
  // - Marathi uses Devanagari (same script as Hindi) → Hindi fallback is readable.
  // - All other non-Hindi scripts → fall back to English to avoid unreadable Devanagari.
  if (entry[code]) return entry[code] as string;
  if (code === 'mr') return entry['hi'] ?? name;
  return name;
}
